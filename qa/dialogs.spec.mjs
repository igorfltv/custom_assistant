import { test, expect } from "@playwright/test";

test("administrator opens and inspects a declaration from the dialogue journal", async ({ page }) => {
  await page.goto("/admin/");
  await page.getByLabel("Email", { exact: true }).fill("qa@example.test");
  await page.getByLabel("Пароль", { exact: true }).fill(process.env.FORMA_QA_PASSWORD);
  await page.getByRole("button", { name: "Войти", exact: true }).click();
  await expect(page.getByRole("link", { name: "Журнал диалогов" })).toBeVisible();
  expect((await page.request.put("/api/admin/providers/deepseek", {
    data: { base_url: "https://api.deepseek.com/v1", api_key: "synthetic-browser-test" },
  })).ok()).toBeTruthy();
  const title = "Проверка журнала поставки";
  const { id } = await (await page.request.post("/api/declarations", { data: { title } })).json();
  const shipment = "/api/declarations/" + id;
  expect((await page.request.post(shipment + "/documents", { multipart: {
    file: { name: "invoice.txt", mimeType: "text/plain", buffer: Buffer.from("Pump P1 100 kg 50 EUR. Declarant: QA Company") },
  } })).ok()).toBeTruthy();
  expect((await page.request.post(shipment + "/analyze")).ok()).toBeTruthy();
  await page.getByRole("link", { name: "Журнал диалогов" }).click();
  const search = page.getByRole("searchbox", { name: "Поиск по журналу" });
  const kind = page.getByLabel("Тип диалога");
  const submit = page.getByRole("button", { name: "Найти" });
  await expect(page.getByRole("link", { name: title, exact: true })).toBeVisible();
  const [inputBox, kindBox, buttonBox] = await Promise.all([search, kind, submit].map(control => control.boundingBox()));
  expect(Math.abs(inputBox.y - kindBox.y)).toBeLessThan(2);
  expect(Math.abs(inputBox.y - buttonBox.y)).toBeLessThan(2);
  expect(inputBox.width).toBeGreaterThan(kindBox.width);
  expect(inputBox.height).toBeLessThan(60);
  await kind.selectOption("knowledge");
  await expect(page.getByRole("link", { name: title })).toHaveCount(0);
  await kind.selectOption("declaration");
  await search.fill("missing-" + id);
  await search.press("Enter");
  await expect(page.getByText("Диалоги не найдены.")).toBeVisible();
  await page.getByRole("button", { name: "Сбросить фильтры" }).click();
  await expect(search).toHaveValue("");
  await expect(kind).toHaveValue("");
  await expect(page.getByRole("link", { name: title, exact: true })).toBeVisible();
  await page.setViewportSize({ width: 390, height: 844 });
  const [mobileInput, mobileKind, mobileSubmit] = await Promise.all([search, kind, submit].map(control => control.boundingBox()));
  expect(mobileInput.y + mobileInput.height).toBeLessThan(mobileKind.y);
  expect(Math.abs(mobileKind.y - mobileSubmit.y)).toBeLessThan(2);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await kind.selectOption("declaration");
  await search.fill(id);
  await submit.click();
  await page.getByRole("link", { name: title, exact: true }).click();
  await expect(page.getByRole("heading", { name: "История диалога" })).toBeVisible();
  await page.locator("summary").filter({ hasText: "Шагов агента" }).click();
  await expect(page.locator(".log-steps")).toContainText("Чтение документа");
  await expect(page.locator(".log-steps")).toContainText("Извлечение фактов из комплекта");
  await page.locator("summary").filter({ hasText: "Вопросы после анализа" }).click();
  await expect(page.getByText(/Графа 1 ·/).first()).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.getByRole("link", { name: "← Журнал диалогов" }).click();
  await expect(search).toHaveValue(id);
  await expect(kind).toHaveValue("declaration");
  await expect(page.getByRole("link", { name: title, exact: true })).toBeVisible();
  await page.getByRole("link", { name: title, exact: true }).click();
  await page.getByRole("link", { name: "Открыть трассировку" }).click();
  await expect(page.getByRole("heading", {name: "Шкала выполнения"})).toBeVisible();
  const steps = page.getByRole("region", {name: "Шаги запуска"});
  await steps.getByRole("button", {name: /^Операции/}).click();
  const phase = steps.locator("details").filter({has: page.locator("summary", {hasText: "Извлечение фактов из комплекта"})});
  await phase.locator("summary").focus();
  await page.keyboard.press("Enter");
  await expect(phase.getByText("extract_facts", {exact:true})).toBeVisible();
  await phase.getByRole("button",{name:"Шаги в этом интервале"}).click();
  await steps.getByRole("button",{name:/^Модели/}).click();
  await expect(steps.locator("summary").first()).toContainText("Извлечение сведений");
  await steps.getByRole("button",{name:"Весь запуск"}).click();
  await steps.getByRole("combobox",{name:"Порядок шагов"}).selectOption("duration");
  await steps.getByRole("searchbox").fill("invoice.txt");
  await expect(steps.locator("summary").first()).toContainText("Чтение документа");
  await steps.getByRole("searchbox").fill("unknown-step");
  await expect(steps.getByText("Подходящих шагов нет")).toBeVisible();
  await steps.getByRole("button", {name:"Сбросить фильтры"}).click();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.getByRole("link",{name:"Все запуски"}).click();
  await page.getByRole("searchbox",{name:"Поиск запусков"}).fill(id);
  await page.getByRole("button",{name:"Найти",exact:true}).click();
  await expect(page.locator(".debug-runs li")).toHaveCount(1);
  await page.getByRole("button",{name:"С ошибкой"}).click();
  await expect(page.getByText("Запуски не найдены")).toBeVisible();
  await page.getByRole("button",{name:"Сбросить фильтры"}).click();
  await expect(page.locator(".debug-runs")).toContainText(title);
});

test("active trace refresh preserves the inspected step and stops on completion", async ({ page }) => {
  await page.goto("/admin/");
  await page.getByLabel("Email", { exact: true }).fill("qa@example.test");
  await page.getByLabel("Пароль", { exact: true }).fill(process.env.FORMA_QA_PASSWORD);
  await page.getByRole("button", { name: "Войти", exact: true }).click();
  await expect(page.getByRole("link", {name:"Отладка агента"})).toBeVisible();
  const path="/api/admin/debug/declaration/active-fixture";
  const start="2026-11-27T12:00:00Z";
  let polls=0, done=false;
  await page.route(path, route => {
    polls++;
    const sampled=new Date(Date.parse(start)+polls*5000).toISOString();
    const state={status:done?"completed":"running", started_at:start, finished_at:done?sampled:null};
    return route.fulfill({json:{...state, id:"active-fixture",kind:"declaration", dialog_id:"dialog",
      title:"Проверка живой трассировки",owner:"QA",queued_at:start,sampled_at:sampled, partial:false,
      steps:[{...state,id:"step",stage:"ocr",kind:"model",requests:polls,retried:polls>1,details:{model:"qa-ocr"}}]}});
  });
  await page.route(path+"/steps/step",route=>route.fulfill({json:{request_id:"qa-request"}}));
  await page.clock.install();
  await page.goto("/admin/#/debug/declaration/active-fixture");
  const row=page.locator("details.debug-step");
  await row.locator("summary").click();
  await expect(row.getByText("qa-request")).toBeVisible();
  await page.getByRole("button",{name:/Автообновление/}).click();
  await page.clock.fastForward(6000);
  expect(polls).toBe(1);
  await page.getByRole("button",{name:"Возобновить"}).click();
  await page.clock.fastForward(5500);
  await expect(row.locator("summary")).toContainText("Повтор");
  await expect(row.getByText("qa-request")).toBeVisible();
  done=true;
  await page.clock.fastForward(5500);
  await expect(row.locator("summary")).toContainText("Завершён");
  await expect(page.getByRole("button",{name:/Автообновление/})).toHaveCount(0);
  await page.clock.fastForward(11000);
  expect(polls).toBe(3);
});
